REQUIRED_VM_OUTPUT_HEX = "24d2da3e7fbc2a5c4bc60bb1338ef5bc2bdb32ba5589780900f265336af97759554ad1a4bdc35ceb779f08dbc1f9b821802f23ed5222d2f48cf1f9c60fe3f2e83f52806dfc12c4fe"


def parse_vm():
    data = bytes.fromhex(''.join(VM_HEX.split()))
    if len(data) % 8 != 0:
        raise ValueError('bad VM length')
    records = [data[i:i+8] for i in range(0, len(data), 8)]
    info = []
    stage = 1
    for rec in records:
        sem = OPMAP[stage][rec[0]]
        info.append((stage, sem, rec))
        if sem == 7:
            stage += 1
        elif sem == 8:
            break
    return records, info


def forward_vm(input_bytes):
    """Forward emulator used only as a sanity check."""
    if len(input_bytes) != 70:
        raise ValueError('input must be 70 bytes')
    _, info = parse_vm()
    st = [0] * 72
    for _stage, sem, r in info:
        if sem == 1:
            st[r[1]] = input_bytes[r[2]]
        elif sem == 2:
            st[r[1]] = 256
        elif sem == 3:
            d, a = r[1], r[2]
            st[d] = (st[d] + (r[3] - r[4]) * st[a] + r[5] - r[6]) % MOD
        elif sem == 4:
            d, a, b = r[1], r[2], r[3]
            st[d] = (st[d] + r[4] * st[a] * st[b] + r[5] * st[a] + r[6] - r[7]) % MOD
        elif sem == 5:
            a, b = r[1], r[2]
            st[a], st[b] = st[b], st[a]
        elif sem in (6, 7):
            pass
        elif sem == 8:
            break
    return st


def invert_vm(target_state):
    """Invert records from the end of stage 13 back to the initial input state."""
    _, info = parse_vm()
    st = list(target_state)

    # Records 3517..3589 are stage-14 copy/halt and do not alter T[349][10].
    # Record 72 is the stage marker. Reverse stage 2..13 payload records only.
    for i in range(3516, 72, -1):
        _stage, sem, r = info[i]
        if sem == 3:
            d, a = r[1], r[2]
            st[d] = (st[d] - ((r[3] - r[4]) * st[a] + r[5] - r[6])) % MOD
        elif sem == 4:
            d, a, b = r[1], r[2], r[3]
            delta = r[4] * st[a] * st[b] + r[5] * st[a] + r[6] - r[7]
            st[d] = (st[d] - delta) % MOD
        elif sem == 5:
            a, b = r[1], r[2]
            st[a], st[b] = st[b], st[a]
        elif sem in (1, 2, 6, 7, 8):
            pass
        else:
            raise RuntimeError(f'unknown semantic op {sem}')
    return st


def recover_flag():
    target_bytes = bytes.fromhex(REQUIRED_VM_OUTPUT_HEX)
    zero_positions = [i for i, b in enumerate(target_bytes) if b == 0]

    # This target has one zero byte. Runtime arithmetic is mod 257, so try both
    # raw representatives for byte 0. Only one produces printable uiuctf{...}.
    choices = [0, 256] if zero_positions else [None]
    for zero_value in choices:
        target = list(target_bytes)
        if zero_positions:
            target[zero_positions[0]] = zero_value

        init = invert_vm(target)
        if init[70] != 256 or init[71] != 256:
            continue
        if any(not (0 <= x < 256) for x in init[:70]):
            continue

        flag = bytes(init[:70])
        if not (flag.startswith(b'uiuctf{') and flag.endswith(b'}')):
            continue
        if bytes(x % 256 for x in forward_vm(flag)) != target_bytes:
            continue
        return flag.decode()

    raise RuntimeError('flag not recovered')


