data1 = [0x98, 0x11, 0x77, 0x39, 0x4f, 0x49, 0x33, 0x25, 0x85, 0x43, 0x9c, 0xf3, 0x42, 0x37]
data2 = [0x6a, 0x82, 0x39, 0x6c, 0x3c, 0x29, 0x62, 0x16, 0x1d, 0x94, 0xa1, 0x5a, 0xb6, 0xd3]

seed = 0x1337
flag = [0] * 28

for i in range(14):
    c1 = (data1[i] - i - (seed & 0xFF)) & 0xFF
    c2 = (data2[i] + i + (seed >> 8)) & 0xFF
    
    flag[i] = chr(c1)
    flag[27-i] = chr(c2)
    
    # Update seed
    val = ((seed ^ c1) + c2) & 0xFFFF
    seed = ((val << 3) | (val >> 13)) & 0xFFFF

print("".join(flag))
