# Kunci yang diekstrak dari main (rbx = 0, 3, 6, 9, 12, 15, 18, 21, 24, 27)
# Mengikuti logika stack [rsp+0x20] yang diisi 0x2050 dan 0x2060
key_source = [
    0xa1, 0xb2, 0xc3, 0xd4, 0xe5, 0xf6, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, # dari 0x2050
    0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0x12, 0x34, 0x56, 0x78, 0x90, 0xab, 0xcd, 0xef # dari 0x2060
]

# rbx index: 0, 3, 6, 9 (dari blok 1)
# rbx index: 12, 15, 18, 21, 24, 27 (dari blok 2)
indices = [0, 3, 6, 9, 12, 15, 18, 21, 24, 27]
key = [(key_source[i] & 0x7F) for i in indices]

# Data terenkripsi dari 0x4080
encrypted_data = [
    0x60, 0x2c, 0x78, 0x2b, 0x1a, 0x51, 0x6c, 0x06, 0x25, 0x58, 
    0x7e, 0x60, 0x4e, 0x26, 0x46, 0x46, 0x31, 0x05, 0x20, 0x01, 
    0x7e, 0x39, 0x20, 0x27, 0x05, 0x1a, 0x2e, 0x57, 0x20, 0x1f, 
    0x12, 0x0b, 0x20, 0x71, 0x28, 0x44, 0x6d, 0x03, 0x78, 0x5e, 
    0x4f, 0x62
]

# Dekripsi menggunakan Repeating XOR
flag = ""
for i in range(len(encrypted_data)):
    flag += chr(encrypted_data[i] ^ key[i % len(key)])

print(f"Flag: {flag}")
